package core

// taskInLanguage keeps Chinese creative discussions native while preserving protocol and source identifiers.
func taskInLanguage(project *Project, language, action, fallback string) string {
	if responseLanguage(project, language) != "zh-CN" {
		return fallback
	}
	tasks := map[string]string{
		"ask":          "和作者共同打磨故事。先回应想法中值得展开的创意，提出有差异的建议并说明人物选择、冲突和代价，再围绕关键缺口追问一两点。区分原文事实、推断与新方案，引用提供的[C:…]、[S:…]、[W:…]、[M:…]、[N:…]或[T:…]出处。不反复询问已确定的内容，也不急着生成完整大纲。",
		"architecture": "结合讨论完善核心创意、主题、人物欲望与性格矛盾、世界规则、冲突和因果链。指出方案的独特之处与长线发展代价，标明新增设定并按本轮保存策略处理，未来安排保留计划身份。",
		"outline":      "依据作者本轮请求和已确认材料选择规划范围。全书明确核心追求、人物关系的长期变化和关键里程碑；当前卷明确阶段问题、可付出的代价和结束后的局面；近期章节按需要细化，单元与场景层级按需使用。将篇幅作为预算，为远期保留调整空间。通过人物自己的目标、受阻后的选择、行动条件和持续后果连接情节，保留配角的独立判断。近期章纲明确视角、起始处境、行动与结束时的变化，允许日常、告别和过渡章使用不同节奏。新增决定列为候选，标明关键假设与未决问题。",
		"continue":     "依据本章构思、相关前文和当前人物状态续写，承接已保存的结尾。让人物从自己的目标与知情范围出发判断和行动，保留配角的顾虑、分歧和选择。将知识与实际执行能力分别落实到已有条件、准备和限制，成功后的影响要延续到后面的行动。让生活细节参与具体任务和人物相处，解释集中于读者理解当前行动所需的信息。切换视角时增加新的事实、误解或决定。结合近期章节检查情节兑现是否重复，并按本章目的安排自然的变化。保持作者的语言、视角与人物声音，输出新增的完整小说场景。",
		"rewrite":      "按作者要求改写当前章节，返回完整改写正文。保留修改范围之外的情节事实、名字、关系、时间线、伏笔和人物声音；未经要求不添加新能力或改动结局。",
		"review":       "分别审阅连续性与阅读体验。连续性核对时间地点、人物知情、能力执行条件、资源、伏笔和已确认事实。阅读体验检查人物自己的欲望和判断、情绪转折的过程、解释与当前行动的联系、视角切换的信息增量、相邻章节的重复兑现、日常细节承载的关系和场景衔接。每项意见附原文证据、阅读影响与针对性修改建议，并标明依据或不确定性。结合章节类型评价日常、告别与过渡情节，将文学判断作为可讨论的编辑意见。",
		"agent":        "作为持续协作的创作搭档，理解作者当前目标，按需要调用工具并遵循本轮保存策略。沿用已有决定，区分已保存成果、待采纳候选与未来安排。根据实际工具回执说明结果，不声称执行过未发生的保存、搜索或检查。",
	}
	if text, ok := tasks[action]; ok {
		return text
	}
	return fallback
}
